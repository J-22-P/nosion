import { describe, expect, it } from 'vitest';
import { toCsv } from './csv';

describe('toCsv', () => {
  it('ขึ้นต้นด้วย BOM และใช้ CRLF ระหว่างแถว', () => {
    expect(
      toCsv([
        ['a', 'b'],
        [1, 2],
      ]),
    ).toBe('﻿a,b\r\n1,2');
  });

  it('ครอบช่องที่มี , " หรือขึ้นบรรทัดใหม่ · " ข้างในกลายเป็น ""', () => {
    expect(toCsv([['ข้าว, ไข่', 'ร้าน "เจ๊"', 'บรรทัด\nใหม่']])).toBe(
      '﻿"ข้าว, ไข่","ร้าน ""เจ๊""","บรรทัด\nใหม่"',
    );
  });

  it('กัน CSV injection แต่ตัวเลขติดลบยังเป็นตัวเลข', () => {
    expect(toCsv([['=SUM(A1)', '-145.00', '+66812345678', null]])).toBe(
      "﻿'=SUM(A1),-145.00,'+66812345678,",
    );
  });
});
